-- #
-- #  Finalidade: geradores de PK. Criados ANTES das tabelas porque 26 das 30
-- #  tabelas referenciam a sequence na expressao DEFAULT da PK
-- #  (DEFAULT SEQ_X.NEXTVAL - sintaxe Oracle 12c+, confirmada disponivel na
