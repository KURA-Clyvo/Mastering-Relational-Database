        DBMS_OUTPUT.PUT_LINE('     NEW: ' || NVL(SUBSTR(r_audit.DS_VALORES_NOVOS,      1, 200), '(vazio)'));
 
        v_total := v_total + 1;
    END LOOP;
    CLOSE c_audit;
 
